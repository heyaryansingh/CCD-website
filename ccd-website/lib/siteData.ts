// =============================================================================
// CONTENT LOADER (client-safe)
//
// Everything on this site is edited in the CMS at /admin and stored as JSON in
// `content/`. This file loads the collections and re-exports them under the same
// names the components have always used, so nothing downstream had to change.
//
// IMPORTANT — why collections are imported here but pages are not:
// This module is imported by components/ClientBits.tsx, which is "use client".
// Anything in this import chain is bundled for the browser, so it must not touch
// the filesystem. Collections are therefore plain `import`s of single JSON files.
// PAGES live in `lib/pages.server.ts` instead, where fs is allowed, because they
// are one-file-per-page so editors can add and delete whole pages.
//
// Editors: do not edit this file. Content is at /admin.
// =============================================================================

