// `resolve` swaps {{settings}} tokens for their live values — see lib/content.ts.
const load = <T,>(payload: { items: unknown[] }): T[] => resolve(payload.items) as T[];

// --- Navigation -------------------------------------------------------------

type NavLink = { label: string; href: string };
type NavGroup = { key: string; label: string; href: string; active: ActiveNav; items: NavLink[] };

export const navigation = navigationData as unknown as {
  groups: NavGroup[];
  simpleLinks: { label: string; href: string; active: ActiveNav }[];
  utilityLinks: NavLink[];
  donateCta: NavLink;
  footerColumns: { title: string; links: NavLink[] }[];
  aliases: Record<string, string>;
};

export const navGroups = navigation.groups;
export const aliases = navigation.aliases;

